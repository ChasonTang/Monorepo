#!/usr/bin/env bash
# Generate the GN header lists from the checked-out googletest submodule.
# Usage: ./util/update_googletest_headers.sh [--check]
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd -P)"
cd "$REPO_ROOT"
export LC_ALL=C
shopt -s nullglob

fail() {
    printf 'update_googletest_headers: %s\n' "$*" >&2
    exit 1
}

if [ "$#" -gt 1 ] || { [ "$#" -eq 1 ] && [ "$1" != --check ]; }; then
    fail "usage: ./util/update_googletest_headers.sh [--check]"
fi

GTEST_INCLUDE=googletest/googletest/include/gtest
GMOCK_INCLUDE=googletest/googlemock/include/gmock
OUTPUT=build/secondary/googletest/headers.gni

for header_dir in "$GTEST_INCLUDE" "$GTEST_INCLUDE/internal" \
                  "$GMOCK_INCLUDE" "$GMOCK_INCLUDE/internal"; do
    [ -d "$header_dir" ] || fail "missing $header_dir; run git submodule update --init googletest"
done

write_header_list() {
    local list_name="$1"
    shift
    [ "$#" -gt 0 ] || fail "no headers found for $list_name; check the upstream layout"

    printf '%s = [\n' "$list_name"
    printf '  "//%s",\n' "$@"
    printf ']\n'
}

# Write beside the destination so publishing the complete list is atomic.
TEMP_FILE="$(mktemp "${OUTPUT}.XXXXXX")"
trap 'rm -f "$TEMP_FILE"' EXIT
trap 'exit 1' HUP INT TERM
{
    printf '# Generated by util/update_googletest_headers.sh. Do not edit.\n'
    printf '# Public: include/{gtest,gmock}/*.h; internal: internal/*.h and internal/*/*.h.\n\n'
    write_header_list gtest_public_headers "$GTEST_INCLUDE"/*.h
    printf '\n'
    write_header_list gtest_internal_headers \
        "$GTEST_INCLUDE"/internal/*.h "$GTEST_INCLUDE"/internal/*/*.h
    printf '\n'
    write_header_list gmock_public_headers "$GMOCK_INCLUDE"/*.h
    printf '\n'
    write_header_list gmock_internal_headers \
        "$GMOCK_INCLUDE"/internal/*.h "$GMOCK_INCLUDE"/internal/*/*.h
} > "$TEMP_FILE"

if cmp -s "$TEMP_FILE" "$OUTPUT"; then
    printf '%s is up to date.\n' "$OUTPUT"
elif [ "${1:-}" = --check ]; then
    fail "$OUTPUT is missing or stale; run ./util/update_googletest_headers.sh"
else
    chmod 644 "$TEMP_FILE"
    mv -f "$TEMP_FILE" "$OUTPUT"
    printf 'Updated %s.\n' "$OUTPUT"
fi
